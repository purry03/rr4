#!/usr/bin/env python3
"""Generate src/material_data.gen.cpp from the original Shockwave 3D stream.

The packed asset file keeps one texture and the diffuse colour per shader.
The original lighting also needs, per shader, its material resource
(ambient, diffuse, specular, emissive, shininess: block type 0x10), the
shader's texture layers (block 0x36; the car shells and windows add
BitsasushiTextureReflectionMap_002 in reflection mode at blend 0.5), and the
scene lights (light resources 0x50, light nodes 0x71).

Also writes the reflection map (a 2 x 32 JPEG) to assets/ReflectionMap.jpg.

Usage: python3 tools/gen_materials.py [XMED-6650.bin] [out.cpp]
"""

import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "work/dump2/redlinerumble4/chunks/XMED-6650.bin"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/material_data.gen.cpp"
REFLECTION = b"BitsasushiTextureReflectionMap_002"

d = open(SRC, "rb").read()


def blocks(tag):
    i = 0
    while True:
        i = d.find(bytes([tag]) + b"\xff\xff\xff", i)
        if i < 0:
            return
        size = struct.unpack_from("<I", d, i + 4)[0]
        if 0 < size < 4000000:
            yield d[i + 8:i + 8 + size]
        i += 4


def name(b, o):
    n = struct.unpack_from("<H", b, o)[0]
    return b[o + 2:o + 2 + n], o + 2 + n


def materials():
    out = {}
    for b in blocks(0x10):
        n, o = name(b, 0)
        f = struct.unpack_from("<18f", b, o + 4)
        out[n] = {"ambient": f[0:3], "diffuse": f[4:7], "specular": f[8:11],
                  "emissive": f[12:15], "shininess": f[16]}
    return out


def shaders():
    out = {}
    for b in blocks(0x36):
        n, o = name(b, 0)
        o += 8                      # flags, count
        mat, o = name(b, o)
        reflect = 0.0
        first = True
        while o + 2 < len(b):
            if not first:
                o += 1              # layer separator
            first = False
            tex, o = name(b, o)
            o += 4                  # intensity
            o += 2                  # blend function, blend source
            const = struct.unpack_from("<f", b, o)[0]
            o += 4
            mode = b[o]
            o += 1 + 128            # texture transform + wrap transform
            if tex == REFLECTION and mode == 4:
                reflect = const
        out[n] = (mat, reflect)
    return out


def lights():
    res = {}
    for b in blocks(0x50):
        n, o = name(b, 0)
        kind = b[o]
        col = struct.unpack_from("<3f", b, o + 2)
        res[n] = (kind, col)
    out = []
    for b in blocks(0x71):
        n, o = name(b, 0)
        _, o = name(b, o)           # parent
        m = struct.unpack_from("<16f", b, o + 3)
        kind, col = res[n]
        # A directional light shines down its node's -Z: toward the light is +Z.
        out.append((n.decode(), kind, col, m[8:11]))
    return out


def reflection_jpeg():
    for b in blocks(0x21):
        n, _ = name(b, 0)
        if n == REFLECTION:
            return b[b.find(b"\xff\xd8"):b.rfind(b"\xff\xd9") + 2]
    raise SystemExit("reflection map not found")


def f3(v):
    return "{%.4ff, %.4ff, %.4ff}" % tuple(v)


def main():
    mats = materials()
    lines = ["// Generated by tools/gen_materials.py from the original 3D stream.",
             "// Do not edit.", '#include "assets.hpp"', "", "namespace rr4 {", "",
             "const ShaderLighting kShaderLighting[] = {"]
    for n, (mat, reflect) in sorted(shaders().items()):
        m = mats.get(mat)
        if not m:
            continue
        lines.append('    {"%s", %s, %s, %s, %s, %.4ff, %.2ff},' % (
            n.decode(), f3(m["ambient"]), f3(m["diffuse"]), f3(m["specular"]),
            f3(m["emissive"]), m["shininess"], reflect))
    lines.append("};")
    lines.append("const int kShaderLightingCount = int(sizeof(kShaderLighting) / sizeof(kShaderLighting[0]));")
    lines.append("")
    lines.append("// Scene lights: kind 0 ambient, 1 directional (direction toward the light).")
    lines.append("const SceneLight kSceneLights[] = {")
    for n, kind, col, z in lights():
        lines.append('    {%d, %s, %s},   // %s' % (kind, f3(col), f3(z), n))
    lines.append("};")
    lines.append("const int kSceneLightCount = int(sizeof(kSceneLights) / sizeof(kSceneLights[0]));")
    lines.append("")
    lines.append("} // namespace rr4")
    open(OUT, "w").write("\n".join(lines) + "\n")
    open("assets/ReflectionMap.jpg", "wb").write(reflection_jpeg())
    print("wrote %s and assets/ReflectionMap.jpg" % OUT)


if __name__ == "__main__":
    main()
