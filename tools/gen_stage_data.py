#!/usr/bin/env python3
"""Generate src/stage_data.gen.cpp (the point stages / time attacks) from
BehaviorScript 4 - PlayerCar.ls: doSetupPointsFlag (pointsFlagPosList,
pointsFlagRotList) and doSetupPointPods (stagePodPosList).

Usage: python3 tools/gen_stage_data.py [PlayerCar.ls] [out.cpp]
"""

import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else \
    "work/dump/redlinerumble4/casts/Internal/BehaviorScript 4 - PlayerCar.ls"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/stage_data.gen.cpp"
VEC = re.compile(r"vector\(([-\d.]+), ([-\d.]+), ([-\d.]+)\)")


def vecs(line):
    return [tuple(float(v) for v in m) for m in VEC.findall(line)]


def f3(v):
    return "{%.2ff, %.2ff, %.2ff}" % v


def main():
    lines = open(SRC, encoding="latin1").read().split("\n")
    flags = rots = None
    pods = []
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith("pointsFlagPosList = ["):
            flags = vecs(s)
        elif s.startswith("pointsFlagRotList = ["):
            rots = [v[1] for v in vecs(s)]
        elif s.startswith("tempList = [vector") and "stagePodPosList.add(tempList)" in lines[i + 1]:
            pods.append(vecs(s))
    assert flags and rots and len(pods) == len(flags) == 8
    out = ["// Generated by tools/gen_stage_data.py from BehaviorScript 4 - PlayerCar.ls.",
           "// Do not edit.", '#include "stage.hpp"', "", "#include <iterator>", "",
           "namespace rr4 {", ""]
    for n, p in enumerate(pods, 1):
        out.append("const Vec3 kStage%dPods[] = {" % n)
        out += ["    %s," % f3(v) for v in p]
        out.append("};")
    out.append("")
    out.append("const StageDef kStages[8] = {")
    for n in range(8):
        out.append("    {%s, %.1ff, kStage%dPods, int(std::size(kStage%dPods))},"
                   % (f3(flags[n]), rots[n], n + 1, n + 1))
    out += ["};", "", "} // namespace rr4"]
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote %s (%s pods)" % (OUT, [len(p) for p in pods]))


if __name__ == "__main__":
    main()
