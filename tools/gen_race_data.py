#!/usr/bin/env python3
"""Generate src/race_data.gen.cpp and src/traffic_data.gen.cpp from the
original MapData cast.

doLoadData reads member(i + 1, "MapData").text for race i: a Lingo list
[[redDot x/10, y/10, z/10 ...], [checkpoint indices into the red dots]]. The
red dots are the opponent's path (redDotPosList) and the checkpoints become
the race pods (racePodPosList). Races 1..5 are MapData members 2..6.

MapData member 1 is the traffic network doLoadData reads first:
[[dot x/10, y/10, z/10 ...], nextDotIDList, prevDotIDList,
 redTrafficLightIDList, greenTrafficLightIDList, tileDotIDList], all ids
1-based. It becomes src/traffic_data.gen.cpp.

Usage: python3 tools/gen_race_data.py [dump2_chunks] [out.cpp] [traffic_out.cpp]
"""

import ast
import os
import re
import sys

CHUNKS = sys.argv[1] if len(sys.argv) > 1 else "work/dump2/redlinerumble4/chunks"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/race_data.gen.cpp"
TRAFFIC_OUT = sys.argv[3] if len(sys.argv) > 3 else "src/traffic_data.gen.cpp"
TRAFFIC = 7136                                             # MapData member 1
RACES = {1: 7138, 2: 7140, 3: 7142, 4: 7144, 5: 7146}   # race -> XMED section


def field_text(section):
    raw = open(os.path.join(CHUNKS, "XMED-%d.bin" % section), "rb").read()
    # The text is stored as "<hex length>,<text>"; the text starts "[[[".
    comma = raw.find(b",[[[")
    j = comma
    while j > 0 and raw[j - 1:j] in b"0123456789ABCDEF":
        j -= 1
    end = comma + 1 + int(raw[j:comma], 16)
    text = raw[comma + 1:end]
    # Long fields continue in further "0002" text blocks of the same form.
    while True:
        m = re.match(rb"\x030002[0-9A-F]{16}\x00?([0-9A-F]+),", raw[end:])
        if not m:
            break
        start = end + m.end()
        end = start + int(m.group(1), 16)
        text += raw[start:end]
    return text.decode("latin1")


def id_table(name, lists):
    """Flatten 1-based id lists into <name>Start (count + 1 offsets) and <name>Ids."""
    starts, ids = [0], []
    for ls in lists:
        ids.extend(ls)
        starts.append(len(ids))
    return ["const int %sStart[] = {%s};" % (name, ", ".join(map(str, starts))),
            "const int %sIds[] = {%s};" % (name, ", ".join(map(str, ids)) or "0")]


def write_traffic():
    dots, nxt, prv, red, green, tiles = ast.literal_eval(field_text(TRAFFIC))
    lines = ["// Generated by tools/gen_race_data.py from MapData member 1 (doLoadData).",
             "// Do not edit.",
             '#include "traffic.hpp"', "", "#include <iterator>", "", "namespace rr4 {", "",
             "const Vec3 kTrafficDotPos[] = {"]
    for x, y, z in dots:
        lines.append("    {%d.0f, %d.0f, %d.0f}," % (x * 10, y * 10, z * 10))
    lines.append("};")
    lines += id_table("kTrafficNext", nxt)
    lines += id_table("kTrafficPrev", prv)
    lines += id_table("kTrafficTile", tiles)
    lines.append("const int kTrafficRedLights[] = {%s};" % ", ".join(map(str, red)))
    lines.append("const int kTrafficGreenLights[] = {%s};" % ", ".join(map(str, green)))
    lines.append("")
    lines.append("const TrafficMap kTrafficMap = {")
    lines.append("    kTrafficDotPos, int(std::size(kTrafficDotPos)),")
    lines.append("    kTrafficNextStart, kTrafficNextIds, kTrafficPrevStart, kTrafficPrevIds,")
    lines.append("    kTrafficTileStart, kTrafficTileIds, int(std::size(kTrafficTileStart)) - 1,")
    lines.append("    kTrafficRedLights, int(std::size(kTrafficRedLights)),")
    lines.append("    kTrafficGreenLights, int(std::size(kTrafficGreenLights)),")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace rr4")
    open(TRAFFIC_OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%d dots, %d tiles)" % (TRAFFIC_OUT, len(dots), len(tiles)))


def main():
    write_traffic()
    lines = ["// Generated by tools/gen_race_data.py from the original MapData cast.",
             "// Do not edit.",
             '#include "race.hpp"', "", "#include <iterator>", "", "namespace rr4 {", ""]
    for race, section in RACES.items():
        dots, checkpoints = ast.literal_eval(field_text(section))
        lines.append("const Vec3 kRace%dRedDots[] = {" % race)
        for x, y, z in dots:
            lines.append("    {%d.0f, %d.0f, %d.0f}," % (x * 10, y * 10, z * 10))
        lines.append("};")
        lines.append("const int kRace%dCheckpoints[] = {%s};" %
                     (race, ", ".join(str(c) for c in checkpoints)))
        lines.append("")
    lines.append("const RacePath kRacePaths[%d] = {" % len(RACES))
    for race in RACES:
        lines.append("    {kRace%dRedDots, int(std::size(kRace%dRedDots)), kRace%dCheckpoints,"
                     " int(std::size(kRace%dCheckpoints))}," % (race, race, race, race))
    lines.append("};")
    lines.append("")
    lines.append("} // namespace rr4")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%d races)" % (OUT, len(RACES)))


if __name__ == "__main__":
    main()
