#pragma once
// Loader for the original Shockwave 3D scene extracted from
// redlinerumble4.dcr (XMED-6650.bin). Geometry, UVs, normals, materials and
// JPEG/PNG textures are packed into assets/rr4_world.bin by the offline
// exporter; this keeps the game byte-for-byte on the original art.

#include "renderer.hpp"
#include <string>
#include <unordered_map>
#include <vector>

namespace rr4 {

struct AssetGroup {
    uint32_t start = 0;
    uint32_t count = 0;
    int material = -1;
};

struct AssetMesh : Mesh {
    std::string name;
    std::vector<AssetGroup> groups;
    Vec3 min{1e30f, 1e30f, 1e30f}, max{-1e30f, -1e30f, -1e30f};
    void computeBounds();
};

struct AssetMaterial {
    std::string name;
    int texture = -1;
    uint32_t color = 0xffffffffu;
    float opacity = 1.0f;
    bool blend = false;
    SurfaceLighting lighting;   // from the original material resource / shader
    float du = 0.0f, dv = 0.0f; // runtime texture scroll (tile batches)
    // Texture multiplier for drawMesh: only the alpha of `color`; the RGB
    // part reaches the lighting as the diffuse colour instead.
    uint32_t tint() const { return (color & 0xff000000u) | 0x00ffffffu; }
};

// Generated by tools/gen_materials.py (src/material_data.gen.cpp).
struct ShaderLighting {
    const char *name;
    Vec3 ambient, diffuse, specular, emissive;
    float shininess;
    float reflect;   // BitsasushiTextureReflectionMap_002 layer blend
};
extern const ShaderLighting kShaderLighting[];
extern const int kShaderLightingCount;
extern const SceneLight kSceneLights[];
extern const int kSceneLightCount;

struct W3DAssets {
    std::vector<Texture> textures;
    std::vector<AssetMaterial> materials;
    std::vector<AssetMesh> meshes;
    std::unordered_map<std::string, size_t> byName;
    Texture reflectionMap;   // assets/ReflectionMap.jpg
    bool load(const std::string &path);
    const AssetMesh *mesh(const std::string &name) const;
    const Texture *texture(int material) const;
    int meshIndex(const std::string &name) const;
};

extern W3DAssets gAssets;

// Draws every material group of an original W3D mesh using the material's
// texture, diffuse colour and opacity.
// Loads a PNG/JPEG file (original cast bitmaps in assets/hud) as RGBA.
bool loadTexture(const std::string &path, Texture &out);

void drawAssetMesh(Renderer &r, const Camera &cam, const Mat4 &model,
                   const AssetMesh &mesh, bool unlit = false,
                   float alphaScale = 1.0f, bool fog = true, int cull = 1);

// Draw a mesh group by group like drawAssetMesh (opaque first, alpha
// second), letting the caller scroll, tint or hide individual shaders.
template <class Fn>
void drawAssetGroups(Renderer &r, const Camera &cam, const Mat4 &model, const AssetMesh &mesh,
                Fn &&shader) {
    r.setWorldFog();
    for (int pass = 0; pass < 2; ++pass) {
        for (size_t g = 0; g < mesh.groups.size(); ++g) {
            const AssetGroup &grp = mesh.groups[g];
            if (grp.count == 0 || grp.material < 0) continue;
            const AssetMaterial &m = gAssets.materials[size_t(grp.material)];
            if ((pass == 0) == m.blend) continue;
            uint32_t tint = m.tint();
            float du = 0.0f, dv = 0.0f;
            if (!shader(int(g), tint, du, dv)) continue;
            r.setSurface(m.lighting);
            r.setUVOffset(du, dv);
            r.drawMesh(cam, model, mesh, gAssets.texture(grp.material), tint, false,
                       m.blend ? 0 : 1, m.opacity, !m.blend, grp.start, grp.count);
        }
    }
    r.setUVOffset(0.0f, 0.0f);
    r.resetSurface();
}

} // namespace rr4
